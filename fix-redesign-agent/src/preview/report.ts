/** Human-readable review documents written next to the preview, generated from the verification so they cannot drift from what was measured. */

const STATUS_LABEL: Record<FindingOutcome['status'], string> = {
  'partially-verified': 'PARTIAL — some targets verified, others open',
  'fixed-verified': 'fixed (measured)',
  'component-verified': 'DS component (measured)',
  'preserved-by-decision': 'kept by decision',
  'applied-unverified': 'applied, not measurable',
  'not-represented': 'NOT in the preview',
  unresolved: 'UNRESOLVED',
};

export function renderFindingAccounting(v: PreviewVerification): { md: string; json: unknown } {
  const counts = v.findings.reduce<Record<string, number>>((a, f) => ((a[f.status] = (a[f.status] ?? 0) + 1), a), {});
  const md = [
    `# Fix finding accounting (${v.findings.length} findings)`,
    '',
    Object.entries(counts).map(([k, n]) => `${n} ${STATUS_LABEL[k as FindingOutcome['status']]}`).join(' · '),
    '',
    ...(v.preserve ? [`Preserve decisions (properties the Resolver kept as the original): ${v.preserve.verified} preserved-verified, ${v.preserve.failed} changed, ${v.preserve.unverified} unverified (of ${v.preserve.total}).`, ''] : []),
    'A finding is "fixed (measured)" only when its measured properties were read from the rendered preview and match the audit\'s expected values. Anything else is listed with the reason; nothing is marked fixed because an element merely exists.',
    '',
    '| Finding | Section | Control | Status | Route | Text contrast | Detail |',
    '|---|---|---|---|---|---|---|',
    ...v.findings.map((f) => `| ${f.findingId.slice(0, 8)} | ${f.section.slice(0, 28)} | ${f.type}: ${f.label.replace(/\|/g, '/').slice(0, 34)} | ${STATUS_LABEL[f.status]} | ${f.route} | ${f.contrast ? `${f.contrast.ratio}:1 (needs ${f.contrast.required}:1${f.contrast.baselineRatio !== null ? `, original ${f.contrast.baselineRatio}:1` : ''})${f.contrast.passes ? '' : ' ✗'}` : '—'} | ${f.detail.replace(/\|/g, '/').slice(0, 200)} |`),
  ].join('\n');
  return { md: md + '\n', json: { generatedAt: v.generatedAt, counts, findings: v.findings } };
}

export function renderPreviewMd(args: { runId: string; v: PreviewVerification; g: GeneratedPreview; source: string; fidelity?: FidelityReport | null; correction?: CorrectionSummary | null }): string {
  const { v, g } = args;
  const failed = v.checks.filter((c) => c.status === 'fail');
  const notChecked = v.checks.filter((c) => c.status === 'not-checked');
  const unav = v.interactions.filter((i) => i.verdict === 'unavailable');
  const mism = v.interactions.filter((i) => i.verdict === 'mismatch');
  // the same status the CLI, pv-status.json, the preview UI and the G2 note read (a file written before `status` existed derives it from its own fields)
  const status = statusOf(v);
  return `# React preview — ${args.runId}

**URL:** ${v.url}
**Source:** \`${args.source}\` (run \`npm install && npm run dev\` there, or \`pnpm run agent preview ${args.runId}\`)
**Mode:** ${v.mode} · **Sections:** ${v.renderedSectionIds.join(', ') || (v.expectedSectionIds.length ? `${v.expectedSectionIds.join(', ')} (expected; none was measured)` : 'none')}
**Verification:** ${statusHeadline(status)} — ${v.summary.passed} check(s) passed, ${v.summary.failed} failed, ${v.summary.notChecked} not checked${status.verdict === 'pass' && args.correction && !args.correction.required.satisfied ? ` · ${args.correction.required.open.length} required check(s) NOT verified, so the preview is not fully verified` : ''}.

This is a recreation of the page's sections for visual review, generated by the pipeline from the run's own captured evidence. It is not production source and nothing here was published.

## What was generated

- ${g.generatedSections.length} section(s) generated from the captured markup and the CSS rules that apply to them${g.overriddenSections.length ? `; ${g.overriddenSections.length} hand-authored section(s) from the Design Review Resolver (${g.overriddenSections.join(', ')})` : ''}.
- ${g.islandsMounted} design-system component(s) mounted in place of original elements (Button / SectionHeading, from the audit's verified match).
- ${g.assets.written} asset file(s) written locally${g.assets.downloaded ? `, ${g.assets.downloaded} downloaded once at generation time` : ''}${g.assets.failed.length ? `; ${g.assets.failed.length} could not be downloaded` : ''}.

## Required checks and disclosed limitations

${renderStatusMd(status, v)}

## Verification before G2

${v.checks.map((c) => `- [${c.status === 'pass' ? 'x' : c.status === 'fail' ? ' ' : '?'}] ${c.name} — ${c.detail}`).join('\n')}

${failed.length ? `**Failed checks:** ${failed.map((c) => c.id).join(', ')}.` : ''}${notChecked.length ? `\n**Not checked:** ${notChecked.map((c) => c.id).join(', ')}.` : ''}

## Design and state fidelity

${renderFidelityMd(args.fidelity ?? null, args.correction ?? null, v.preserve ?? null, status.verdict === 'pass')}

## Fix findings

${v.summary.findingsVerified}/${v.summary.findingsTotal} verified by measurement in the rendered preview. Per-finding detail: \`finding-accounting.md\`.

## Text contrast

${renderContrastMd(v)}

## Selects and comboboxes

${renderPopupMd(v)}

## Interactions

${v.summary.interactionsTotal} behaviour(s) of the original page were probed: ${v.summary.interactionsMatched} reproduced, ${unav.length} not reproduced, ${mism.length} behave differently.

${v.unavailable.length ? `### Not reproduced or different\n\n${v.unavailable.map((u) => `- ${u}`).join('\n')}` : v.summary.interactionsTotal === 0 ? '_No interaction was probed, so nothing is claimed about the preview\'s behaviour either way._' : '_Nothing was found that the preview fails to reproduce._'}

## Simulated

${v.simulated.map((s) => `- ${s}`).join('\n')}
${rulesMd(g)}`;
}

/** The user instructions and DS structural rules that shaped the generated preview: listed so a reviewer can tell them from the audit's fixes. */
function rulesMd(g: GeneratedPreview): string {
  const lines = [
    ...(g.arrowLinks ? [`- ${g.arrowLinks} arrow link(s) ("Read More ↗") with no mapped finding are the DS CTALink (structural DS rule).`] : []),
    ...(g.badges ? [`- ${g.badges} pill badge(s) with no mapped finding are the DS Badge (structural DS rule).`] : []),
    ...(g.indicatorGroups ? [`- ${g.indicatorGroups} carousel indicator group(s) take the DS indicator colours, 28px bars (structural DS rule).`] : []),
    ...(g.eyebrows?.length ? [`- ${g.eyebrows.length} eyebrow label(s) lost their decorative icon and take the DS SectionLabel style (structural DS rule): ${g.eyebrows.map((e) => `"${e.label}" (${e.sectionId})`).join(', ')}.`] : []),
    ...(g.userRules ?? []).filter((u) => !u.shared || u.matched > 0).map((u) => `- ${u.shared ? 'Shared' : 'User'} style rule "${u.id}" (${u.section}): ${u.matched} element(s) — ${u.reason}${u.matched === 0 ? ' — MATCHED NOTHING, not applied' : ''}`),
  ];
  return lines.length ? `\n## Rules applied beyond the audit's fixes\n\n${lines.join('\n')}\n` : '';
}

/** PASS only when every required check is verified; the unverified and failed required items and the disclosed limitations are listed apart. */
function renderStatusMd(s: ReturnType<typeof statusOf>, v: PreviewVerification): string {
  const lines = [`**${statusHeadline(s)}.** Required = every verification check, the design/state fidelity checks, each resolved target and each preserve decision. A failed required check makes the preview FAIL; a required check that could not be verified makes it INCOMPLETE (never PASS); individual results below are kept as measured.`, ''];
  if (s.gaps.length) {
    lines.push(`Required items not verified (${s.failedRequired} failed, ${s.unverifiedRequired} unverified):`, ...s.gaps.map((g) => `- ${g.kind === 'failed' ? '**FAILED**' : 'UNVERIFIED'} [${g.family}] ${g.text.replace(/\n/g, ' ')}`));
    if (s.gapsTruncated) lines.push(`- …and ${s.gapsTruncated} more (see verification.json, status.gaps)`);
  } else lines.push(`Every required check is verified.${v.summary.findingsTotal > 0 ? ` ${v.summary.findingsVerified} of ${v.summary.findingsTotal} Fix finding(s) measured fixed in the rendered preview (the rest are listed in finding-accounting.md and are not claimed fixed).` : ''}`);
  lines.push('', s.disclosed.length ? 'Disclosed limitations (optional or by design; they never change the verdict):' : 'No optional limitation is disclosed.', ...s.disclosed.map((d) => `- ${d}`));
  if (s.disclosedTruncated) lines.push(`- …and ${s.disclosedTruncated} more`);
  return lines.join('\n');
}

function renderContrastMd(v: PreviewVerification): string {
  const c = v.contrast;
  if (!c) return '_Text contrast was not measured for this run._';
  const verdictLabel = { regression: 'introduced', inherited: 'inherited from the original', unbaselined: 'no original counterpart', pass: 'meets AA' } as const;
  const row = (r: NonNullable<PreviewVerification['contrast']>['rows'][number]) => `| ${r.section.slice(0, 22)} | ${r.text.replace(/\|/g, '/').slice(0, 44)} | ${r.color} on ${r.background} | ${r.ratio}:1 | ${r.required}:1 / ${r.requiredAAA}:1 | ${r.baselineRatio !== null ? `${r.baselineRatio}:1` : '—'} | ${r.passesAA ? 'AA ok, below 7:1' : verdictLabel[r.verdict]} |`;
  const head = '| Section | Text | Colour on background | Measured | Needs (AA / AAA) | Original | Meaning |\n|---|---|---|---|---|---|---|';
  const below = c.rows.filter((r) => !r.passesAA).sort((a, b) => a.ratio - b.ratio);
  const aaOnly = c.rows.filter((r) => r.passesAA);
  return [
    `Measured on the rendered pixels behind ${c.measuredRuns} text run(s) (WCAG 2.x contrast, 5th percentile over the real background, text alpha composited). **Gate: AA** (4.5:1, large text 3:1). The design system's own rule R7.1 asks 7:1 for all text; it is reported alongside, not gated.`,
    '',
    `- ${c.failAA} run(s) below AA — ${c.regressions} introduced by the redesign, ${c.inherited} inherited unchanged from the original page, ${c.unbaselined} with no original counterpart.`,
    `- ${c.failAAA} run(s) below 7:1 (R7.1).`,
    `- Muted labels (reduced alpha or mid-grey text): ${c.mutedRuns} measured, ${c.mutedBelowAA} below AA, ${c.mutedBelowAAA} below 7:1.`,
    '',
    below.length ? `### Below AA\n\n${head}\n${below.map(row).join('\n')}` : '_No text run is below AA._',
    '',
    aaOnly.length ? `### Meets AA, below the design system's 7:1 (R7.1)\n\n${head}\n${aaOnly.map(row).join('\n')}` : '',
  ].join('\n');
}

function renderPopupMd(v: PreviewVerification): string {
  const p = v.popupControls;
  if (!p || p.length === 0) return '_No select or combobox control in these sections._';
  const yn = (b: boolean | null) => (b === null ? 'n/a' : b ? 'yes' : '**NO**');
  return [
    'Each control was opened by click and by keyboard, an option was chosen by keyboard and by click, Escape was pressed, and the focus indicator was compared with idle.',
    '',
    '| Section | Control | Click opens | Options on screen | Panel painted | Esc closes | Enter / Space / ArrowDown | Keyboard pick | Click pick | Focus indicator |',
    '|---|---|---|---|---|---|---|---|---|---|',
    ...p.map((c) => `| ${c.section.slice(0, 20)} | ${c.label.replace(/\|/g, '/')} | ${yn(c.clickOpens)} | ${c.optionsVisible}/${c.optionsInDom} | ${yn(c.panelFilled)} | ${yn(c.escapeCloses)} | ${yn(c.keyboard.enter)} / ${yn(c.keyboard.space)} / ${yn(c.keyboard.arrowDown)} | ${yn(c.keyboardSelects)} | ${yn(c.clickSelects)} | ${yn(c.focusIndicator.present)} |`),
  ].join('\n');
}

function renderFidelityMd(f: FidelityReport | null, c: CorrectionSummary | null, preserve: PreserveSummary | null, overallPass: boolean): string {
  if (!f) return c?.stopReason === 'budget-exhausted'
    ? '_Design and state fidelity was not compared for this run: the correction budget allowed no verification, and no earlier comparison of this plan is kept (see the required items above)._'
    : '_Design and state fidelity was not compared for this run (no baseline of the original was captured)._';
  const s = f.summary;
  const cov = f.coverage;
  const regress = f.differences.filter((d) => d.classification === 'regression');
  const lines = [
    `Compared with the immutable pre-edit baseline${f.baselineSha256 ? ` (\`${f.baselineSha256.slice(0, 12)}\`)` : ''}: **${f.verdict.toUpperCase()}** — ${s.elementsCompared} element(s) across ${s.sectionsCompared}/${s.sections} section(s); default ${s.statesCompared.default}, hover ${s.statesCompared.hover}, keyboard focus ${s.statesCompared['focus-visible']}.`,
    `${s.regressions} regression(s), ${s.intentional} change(s) authorized by a resolved target (finding + property + state), ${s.notCheckable} not checkable.`,
  ];
  if (isIncomplete(f)) lines.push('', `**INCOMPLETE:** no regression was found, but ${cov ? `${cov.requiredUnverified} required check(s) (${splitText(gapSplit(f))})` : 'some required check(s) (no coverage was recorded, so nothing proves which)'} could not be run, so this is not a pass. Verified results below are kept; the unverified checks are listed.`);
  if (cov) {
    lines.push('', '### Coverage', '', `${summarizeCoverage(f)}${cov.requiredUnverified ? ` (${splitText(gapSplit(f))}; by-design = permanent, e.g. a hand-authored section or a state the original could not be captured in)` : ''}.`, '', '| Check | Required | Verified | Failed | Unverified | Not required (disclosed) |', '|---|---|---|---|---|---|');
    for (const fam of COVERAGE_FAMILIES) { const x = cov.families[fam]; lines.push(`| ${fam} | ${x.required} | ${x.verified} | ${x.failed} | ${x.unverified} | ${x.notRequired} |`); }
    const sm = cov.sampling;
    lines.push('', `Sampling: sampled ${sm.hoverSampled} of ${sm.hoverEligible} element(s) (controls and the elements findings name) for hover, ${sm.focusSampled} of ${sm.focusEligible} for keyboard focus${sm.elementsDropped ? `; ${sm.elementsDropped} element(s) beyond the per-section cap were not captured` : ''}${sm.groupsDropped ? `; ${sm.groupsDropped} group(s) beyond the cap` : ''}${sm.stickyInert ? `; ${sm.stickyInert} sticky element(s) that can never pin were not traced` : ''}${sm.islandInternal ? `; ${sm.islandInternal} element(s) inside mounted design-system components belong to the component` : ''}${sm.animationsFrozen ? `; ${sm.animationsFrozen} animated element(s) were frozen at a fixed frame for the default-state capture` : ''}${sm.walkCut ? `; ${sm.walkCut} node(s) beyond the walk limit were not entered` : ''}${sm.hoverSubtreeDropped ? `; ${sm.hoverSubtreeDropped} hover-subtree member(s) beyond the cap were not recorded` : ''}. Disclosed gaps that do not block are in fidelity.json (coverage.gaps).`);
    const req = cov.gaps.filter((g) => g.required);
    if (req.length) {
      lines.push('', '### Required checks not verified', '', ...req.slice(0, 40).map((g) => `- ${g.family}: ${g.sectionId} (${g.viewport})${g.elementKey ? ` / ${g.label}` : ''}${g.state === 'default' ? '' : ` / ${g.state}`} — ${BY_DESIGN_GAP_REASONS.has(g.reason) ? '[by-design] ' : ''}${g.reason}: ${g.detail}`));
      if (cov.requiredUnverified > Math.min(40, req.length)) lines.push(`- …and ${cov.requiredUnverified - Math.min(40, req.length)} more (see fidelity.json, coverage.gaps)`);
    }
  }
  if (preserve && preserve.total > 0) {
    lines.push('', '### Preserved properties', '', `${preserve.verified} preserved-verified, ${preserve.failed} changed, ${preserve.unverified} unverified (of ${preserve.total} preserve decision(s)). A property is preserved-verified only when the same element, part, property, state and viewport were compared on both pages and agree.`);
    if (preserve.reasons.length) lines.push('', 'Not preserved-verified, by reason:', ...preserve.reasons.map((r) => `- ${r.reason}: ${r.count}`));
    if (preserve.worst.length) lines.push('', ...preserve.worst.map((w) => `- ${w.verification === 'failed' ? '**changed**' : 'unverified'} — ${w.property}${w.state === 'default' ? '' : ` [${w.state}]`} (finding ${w.findingId.slice(0, 8)}): ${w.detail}`));
  }
  if (regress.length) lines.push('', '### Regressions', '', ...regress.slice(0, 40).map((d) => `- ${d.sectionId} / ${d.elementLabel} / ${d.state}${d.property ? ` / ${d.property}` : ''} (${d.viewport}): original \`${d.baseline ?? '—'}\`, preview \`${d.observed ?? '—'}\` — ${d.detail}`));
  if (!cov && f.unavailable.length) lines.push('', '### Not checked', '', ...f.unavailable.map((u) => `- ${u}`));
  if (f.statesNotCaptured.length) lines.push('', `Not captured by this verifier: ${f.statesNotCaptured.join('; ')}.`);
  if (c) {
    lines.push('', '### Correction loop', '', `Stopped: **${c.stopReason}**${c.budgetReason ? ` (${c.budgetReason})` : ''} after ${c.cycles.length} correction cycle(s), ${c.verifications} verification(s).`);
    // "holds" needs BOTH the summary's flag and a complete fidelity result: a flag alone never overrides an unverified required check
    const holds = overallPass && c.required.satisfied && c.required.open.length === 0 && f.verdict === 'pass' && !isIncomplete(f);
    const open = c.required.open.length ? c.required.open : holds ? [] : [`design/state fidelity is ${f.verdict.toUpperCase()}${cov ? `: ${summarizeCoverage(f)}` : ''}`];
    lines.push(holds ? '**Every required check holds.**' : `**Required checks still open (${open.length}) — the preview is not fully verified:**\n${open.map((o) => `- ${o}`).join('\n')}`);
    for (const cy of c.cycles) lines.push(`- cycle ${cy.cycle}: ${cy.feedbackIds.length} open → ${cy.applied.join('; ') || 'nothing applied'}${cy.blockedIds.length ? `; blocked: ${cy.blockedIds.join(', ')}` : ''}`);
    if (c.open.length) lines.push('', `**Still open (${c.open.length}):**`, ...c.open.slice(0, 40).map((o) => `- ${o.message}${o.blockedReason ? ` — blocked: ${o.blockedReason}` : ''}`));
  }
  return lines.join('\n');
}
